importScripts('https://www.gstatic.com/firebasejs/9.0.0/firebase-messaging-compat.js');

// This file is static, if you want to use the config dynamically you can fetch it or hardcode it
// For this environment, we'll need to fetch the config or assume it's available
// Since I can't easily inject the config here without a build step, I'll use a placeholder
// real apps usually have this configured during build

const firebaseConfig = {
  // These will be replaced by the app's config
  apiKey: "PLACEHOLDER",
  authDomain: "PLACEHOLDER",
  projectId: "PLACEHOLDER",
  storageBucket: "PLACEHOLDER",
  messagingSenderId: "PLACEHOLDER",
  appId: "PLACEHOLDER"
};

firebase.initializeApp(firebaseConfig);
const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  console.log('[firebase-messaging-sw.js] Received background message ', payload);
  const notificationTitle = payload.notification.title;
  const notificationOptions = {
    body: payload.notification.body,
    icon: '/logo.png'
  };

  self.registration.showNotification(notificationTitle, notificationOptions);
});
